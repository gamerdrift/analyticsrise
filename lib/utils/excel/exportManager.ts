import { Sheet, Cell } from '@/app/excel-studio/contexts/ExcelStudioContext';
import { colIndexToLetter, evaluateFormula } from './formulaEvaluator';

/**
 * Export active worksheet to CSV format string and download
 */
export function exportToCSV(sheet: Sheet, filename: string = 'export.csv') {
  const maxRow = findMaxRow(sheet.cells);
  const maxCol = findMaxCol(sheet.cells);

  const lines: string[] = [];
  for (let r = 0; r <= maxRow; r++) {
    const rowValues: string[] = [];
    for (let c = 0; c <= maxCol; c++) {
      const cell = sheet.cells[`${r},${c}`];
      let valStr = '';
      if (cell) {
        const evaluated = cell.formula ? evaluateFormula(cell.formula, sheet.cells) : cell.value;
        valStr = evaluated !== null && evaluated !== undefined ? String(evaluated) : '';
      }
      // Escape quotes and commas in CSV
      if (valStr.includes(',') || valStr.includes('"') || valStr.includes('\n')) {
        valStr = `"${valStr.replace(/"/g, '""')}"`;
      }
      rowValues.push(valStr);
    }
    lines.push(rowValues.join(','));
  }

  const csvContent = lines.join('\n');
  downloadFile(csvContent, filename, 'text/csv;charset=utf-8;');
}

