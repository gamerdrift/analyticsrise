/**
 * Public Question Representation (Sanitized for client consumption)
 * Learners receive only text, options, and points. Never correct answers or indices.
 */
export interface PublicAssessmentQuestion {
  id: string;
  text: string;
  options: string[];
  points: number;
}

/**
 * Public Assessment Metadata
 */
export interface PublicAssessmentMetadata {
  id: string;
  title: string;
  category: string;
  courseId: string;
  durationMinutes: number;
  passingScore: number;
  totalQuestions: number;
  totalPoints: number;
  difficulty: 'Beginner' | 'Intermediate' | 'Advanced';
  questions: PublicAssessmentQuestion[];
}

/**
 * Server-Only Private Answer Key Definition
 * Stored securely on the server / Firestore /assessmentAnswers/{id}.
 * NEVER exposed to client-side bundles or callable responses.
 */
export interface PrivateQuestionKey {
  correctIndex: number;
  points: number;
}

export interface PrivateAssessmentKey {
  assessmentId: string;
  passingScore: number;
  totalPoints: number;
  keys: Record<string, PrivateQuestionKey>;
}

